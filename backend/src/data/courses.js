function buildModules(topics) {
  return topics.map((topic, index) => ({
    id: index + 1,
    title: topic.title,
    lessons: topic.lessons.map((lesson, lessonIndex) => ({
      id: index * 100 + lessonIndex + 1,
      title: lesson.title,
      type: lesson.type ?? (lessonIndex % 5 === 4 ? "quiz" : "video"),
      duration: lesson.duration ?? `${12 + ((index + lessonIndex) % 5) * 7} min`,
      isPreview: index === 0 && lessonIndex < 2,
    })),
  }));
}

function course(index, data) {
  const id = index + 1;
  return {
    id,
    slug: data.slug,
    title: data.title,
    category: data.category,
    level: data.level,
    mode: data.mode,
    thumbnail: thumb(data.slug, data.title),
    price: data.price,
    originalPrice: data.originalPrice,
    rating: data.rating,
    reviewsCount: data.reviewsCount,
    studentsCount: data.studentsCount,
    duration: data.duration,
    technologies: data.technologies,
    shortDescription: data.shortDescription,
    overview: data.overview,
    outcomes: data.outcomes,
    prerequisites: data.prerequisites,
    audience: data.audience,
    certification: `Verified ${data.title} Certificate`,
    careerOutcomes: data.careerOutcomes,
    isFeatured: Boolean(data.isFeatured),
    status: "active",
    mentorId: ((index % 10) + 1),
    createdAt: new Date(Date.now() - (index + 3) * 86400000).toISOString(),
    modules: buildModules(data.topics),
  };
}

