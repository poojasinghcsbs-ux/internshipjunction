import { thumb } from "../utils/placeholder.js";

const roadmap = (weeks) =>
  weeks.map((week, index) => ({
    week: `Week ${index + 1}`,
    title: week.title,
    tasks: week.tasks,
  }));

function internship(index, data) {
  return {
    id: index + 1,
    slug: data.slug,
    title: data.title,
    domain: data.domain,
    level: data.level,
    mode: data.mode,
    duration: data.duration,
    stipend: data.stipend,
    location: data.location,
    thumbnail: thumb(data.slug, data.domain),
    skills: data.skills,
    shortDescription: data.shortDescription,
    overview: data.overview,
    eligibility: data.eligibility,
    roadmap: roadmap(data.roadmap),
    perks: data.perks,
    certification: "Verified Internship Completion Certificate",
    applicationDeadline: new Date(Date.now() + (index + 5) * 86400000).toISOString().slice(0, 10),
    status: "open",
    openings: data.openings ?? 25,
    applicantsCount: data.applicantsCount ?? 120 + index * 37,
    isFeatured: Boolean(data.isFeatured),
    mentorId: (index % 10) + 1,
  };
}

